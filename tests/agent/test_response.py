"""
Tests for STEP 13 — Final Response Generator Nodes
"""

import pytest
from agent.intents import (
    CLASS_INQUIRY,
    PROJECT_HELP,
    ASSIGNMENT_HELP,
    GENERAL_QUESTION,
    UNKNOWN,
)
from agent.nodes.response import (
    generate_response,
    general_response,
    clarification,
)


def assert_no_internal_jargon(text: str):
    """Verifies that no system internals or raw representations leak into user responses."""
    forbidden = [
        "AgentState",
        "missing_fields",
        "intent_confidence",
        "raw_intent",
        "class_id",
        "StateGraph",
        "None",
        "json",
        "node",
        "routing",
    ]
    for term in forbidden:
        assert term not in text, f"Forbidden internal term '{term}' leaked into user response:\n{text}"


class TestResponseGenerator:
    """Step 13 unit tests for response generation."""

    def test_class_recommendation_response(self):
        state = {
            "intent": CLASS_INQUIRY,
            "recommended_class": "Advanced Python & AI: Build AI Web Apps With React, API & Database",
            "recommended_class_id": "advanced_python_ai_web",
            "recommendation_reason": "Since he already knows basic Python and wants to build AI-based projects, this gives him room to move into APIs, databases, and web apps instead of repeating beginner material.",
        }
        res = generate_response(state)
        assert "response" in res
        text = res["response"]

        assert "Advanced Python & AI" in text
        assert "APIs, databases, and web apps" in text
        assert "free intro call" in text or "enrolling" in text
        assert_no_internal_jargon(text)

    def test_project_help_recommendation_response(self):
        state = {
            "intent": PROJECT_HELP,
            "recommended_class": "Private 1-on-1 Project Tutoring",
            "recommended_class_id": "private_project_tutoring",
            "recommendation_reason": "Provides flexible 1-on-1 mentorship focused directly on helping the student finish a personal travel website with custom codebase support.",
        }
        res = generate_response(state)
        assert "response" in res
        text = res["response"]

        assert "Private 1-on-1 Project Tutoring" in text
        assert "personal travel website" in text
        assert "code and architecture" in text or "project" in text
        assert_no_internal_jargon(text)

    def test_assignment_help_recommendation_response(self):
        state = {
            "intent": ASSIGNMENT_HELP,
            "recommended_class": "AP Computer Science A (Java) Prep & Tutoring",
            "recommended_class_id": "ap_computer_science_java",
            "recommendation_reason": "Offers targeted 1-on-1 coaching covering AP Computer Science Java coursework, object-oriented concepts, and assignment problem-solving.",
        }
        res = generate_response(state)
        assert "response" in res
        text = res["response"]

        assert "AP Computer Science A" in text
        assert "assignment" in text
        assert "review your assignment together" in text
        assert_no_internal_jargon(text)

    def test_existing_response_passthrough(self):
        # Follow-up question generated by followup_question node
        existing_q = "How old is the student, and have they had any prior experience with coding before?"
        state = {
            "response": existing_q,
            "intent": CLASS_INQUIRY,
        }
        res = generate_response(state)
        assert res["response"] == existing_q
        assert_no_internal_jargon(res["response"])

    def test_general_response_node(self):
        state = {"intent": GENERAL_QUESTION}
        res = general_response(state)
        assert "response" in res
        text = res["response"]

        assert "Faruk" in text
        assert "Python & AI" in text
        assert "live" in text or "online" in text
        assert_no_internal_jargon(text)

    def test_clarification_node(self):
        state = {"intent": UNKNOWN}
        res = clarification(state)
        assert "response" in res
        text = res["response"]

        assert "programming courses" in text
        assert "personal software project" in text
        assert "assignment" in text
        assert_no_internal_jargon(text)

    def test_generate_response_delegates_to_clarification_when_empty_state(self):
        state = {}
        res = generate_response(state)
        assert "response" in res
        text = res["response"]
        assert "find the right option" in text
        assert_no_internal_jargon(text)
